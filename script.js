/* ==========================================================================
   Estado Global de la Aplicación
   ========================================================================== */
let currentLang = 'es';
let cart = [];
let activeCategory = 'all';

/* ==========================================================================
   Inicialización
   ========================================================================== */
document.addEventListener('DOMContentLoaded', () => {
  // Inicializar Lucide Icons
  lucide.createIcons();

  // Comprobar si ya existe un idioma guardado en localStorage
  const savedLang = localStorage.getItem('larrainzar_lang');
  
  if (savedLang) {
    currentLang = savedLang;
    applyLanguage(currentLang);
  } else {
    // Si es la primera visita, mostrar el modal de idioma
    document.getElementById('lang-modal').classList.add('active');
  }

  // Renderizar productos
  renderProducts();
});

/* ==========================================================================
   Sistema de Traducción & Idiomas (LocalStorage)
   ========================================================================== */
function selectLanguage(lang) {
  currentLang = lang;
  localStorage.setItem('larrainzar_lang', lang);
  
  // Cerrar Modal
  document.getElementById('lang-modal').classList.remove('active');
  
  // Aplicar cambios
  applyLanguage(lang);
}

function applyLanguage(lang) {
  // Actualizar código en header
  document.getElementById('current-lang-code').innerText = lang.toUpperCase();

  // Traducir elementos con atributo data-i18n
  const elements = document.querySelectorAll('[data-i18n]');
  elements.forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (translations[lang] && translations[lang][key]) {
      el.innerText = translations[lang][key];
    }
  });

  // Traducir Placeholders
  const placeholders = document.querySelectorAll('[data-i18n-placeholder]');
  placeholders.forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (translations[lang] && translations[lang][key]) {
      el.placeholder = translations[lang][key];
    }
  });

  // Volver a renderizar productos por si cambia etiquetas traducidas
  renderProducts();
}

/* ==========================================================================
   Renderizado de Productos & Filtros
   ========================================================================== */
function renderProducts() {
  const catalogGrid = document.getElementById('products-grid');
  const newGrid = document.getElementById('new-products-grid');
  
  catalogGrid.innerHTML = '';
  newGrid.innerHTML = '';

  const searchValue = document.getElementById('search-input')?.value.toLowerCase() || '';

  products.forEach(product => {
    // Filtrado por categoría y búsqueda
    const matchesCategory = activeCategory === 'all' || product.category === activeCategory;
    const matchesSearch = product.title.toLowerCase().includes(searchValue) || product.desc.toLowerCase().includes(searchValue);

    if (matchesCategory && matchesSearch) {
      const card = createProductCard(product);
      catalogGrid.appendChild(card);
    }

    // Renderizar novedades
    if (product.isNew) {
      const newCard = createProductCard(product);
      newGrid.appendChild(newCard);
    }
  });

  // Re-inicializar iconos Lucide generados dinámicamente
  lucide.createIcons();
}

function createProductCard(product) {
  const div = document.createElement('div');
  div.className = 'product-card';
  
  const byText = translations[currentLang]['artisan.by'] || 'Por';
  const addCartText = translations[currentLang]['product.addCart'] || 'Agregar al Carrito';

  div.innerHTML = `
    <div class="product-img-wrapper">
      <img src="${product.image}" alt="${product.title}">
      <span class="product-tag">${product.category}</span>
      <div class="product-actions">
        <button class="action-btn" onclick="openQuickView(${product.id})" title="Ver Detalle">
          <i data-lucide="eye"></i>
        </button>
        <button class="action-btn" onclick="addToCart(${product.id})" title="Agregar">
          <i data-lucide="shopping-bag"></i>
        </button>
      </div>
    </div>
    <div class="product-info">
      <h3 class="product-title">${product.title}</h3>
      <p class="product-artisan">${byText} <strong>${product.artisan}</strong></p>
      <div class="product-bottom">
        <span class="product-price">$${product.price.toLocaleString()} MXN</span>
        <button class="btn btn-primary" style="padding: 6px 12px; font-size:0.75rem;" onclick="addToCart(${product.id})">
          ${addCartText}
        </button>
      </div>
    </div>
  `;
  return div;
}

function filterCategory(cat) {
  activeCategory = cat;
  
  // Actualizar botones activos
  const buttons = document.querySelectorAll('.filter-btn');
  buttons.forEach(btn => btn.classList.remove('active'));
  event.target.classList.add('active');

  renderProducts();
}

function filterProducts() {
  renderProducts();
}

/* ==========================================================================
   Carrito de Compras
   ========================================================================== */
function toggleCart() {
  const drawer = document.getElementById('cart-drawer');
  const overlay = document.getElementById('cart-overlay');
  
  drawer.classList.toggle('active');
  overlay.classList.toggle('active');
}

function addToCart(productId) {
  const product = products.find(p => p.id === productId);
  if (!product) return;

  const existing = cart.find(item => item.id === productId);
  if (existing) {
    existing.quantity++;
  } else {
    cart.push({ ...product, quantity: 1 });
  }

  updateCartUI();
  toggleCart();
}

function updateCartUI() {
  const cartBody = document.getElementById('cart-body');
  const cartCount = document.getElementById('cart-count');
  const cartTotal = document.getElementById('cart-total-price');

  cartBody.innerHTML = '';

  if (cart.length === 0) {
    const emptyText = translations[currentLang]['cart.empty'] || 'Tu carrito está vacío';
    cartBody.innerHTML = `<p style="text-align:center; color:#888; margin-top:40px;">${emptyText}</p>`;
    cartCount.innerText = '0';
    cartTotal.innerText = '$0 MXN';
    return;
  }

  let total = 0;
  let count = 0;

  cart.forEach(item => {
    total += item.price * item.quantity;
    count += item.quantity;

    const div = document.createElement('div');
    div.className = 'cart-item';
    div.innerHTML = `
      <img src="${item.image}" alt="${item.title}">
      <div class="cart-item-info">
        <h4>${item.title}</h4>
        <p>$${item.price.toLocaleString()} MXN x ${item.quantity}</p>
      </div>
      <button onclick="removeFromCart(${item.id})" style="background:none; border:none; color:#800020; cursor:pointer;">&times;</button>
    `;
    cartBody.appendChild(div);
  });

  cartCount.innerText = count;
  cartTotal.innerText = `$${total.toLocaleString()} MXN`;
}

function removeFromCart(productId) {
  cart = cart.filter(item => item.id !== productId);
  updateCartUI();
}

function checkout() {
  if (cart.length === 0) return;
  alert('¡Gracias por apoyar a nuestras artesanas! Esta es una demostración de compra.');
  cart = [];
  updateCartUI();
  toggleCart();
}

/* ==========================================================================
   QuickView Modal
   ========================================================================== */
function openQuickView(productId) {
  const product = products.find(p => p.id === productId);
  if (!product) return;

  document.getElementById('qv-image').src = product.image;
  document.getElementById('qv-category').innerText = product.category;
  document.getElementById('qv-title').innerText = product.title;
  document.getElementById('qv-price').innerText = `$${product.price.toLocaleString()} MXN`;
  document.getElementById('qv-desc').innerText = product.desc;
  document.getElementById('qv-artisan').innerText = product.artisan;
  document.getElementById('qv-time').innerText = product.time;

  const addBtn = document.getElementById('qv-add-btn');
  addBtn.onclick = () => {
    addToCart(product.id);
    closeQuickView();
  };

  document.getElementById('quickview-modal').classList.add('active');
}

function closeQuickView() {
  document.getElementById('quickview-modal').classList.remove('active');
}
